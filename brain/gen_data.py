def pick(a): return random.choice(a)

D = {}
def add(intent, items, sent='neu'):
    D.setdefault(intent, [])
    for x in items:
        if isinstance(x, tuple): D[intent].append(x)
        else: D[intent].append((x, sent))

def expand(pattern):
    # "{a|b|c}" 선택지를 전부 펼친다
    parts = re.split(r'(\{[^}]*\})', pattern)
    outs = ['']
    for p in parts:
        if p.startswith('{'):
            opts = p[1:-1].split('|')
            outs = [o + q for o in outs for q in opts]
        else:
            outs = [o + p for o in outs]
    return [re.sub(r'\s+', ' ', o).strip() for o in outs]

def E(intent, patterns, sent='neu', limit=None):
    out = []
    for pt in patterns:
        out += expand(pt)
    random.shuffle(out)
    if limit: out = out[:limit]
    add(intent, out, sent)

